#!/bin/bash
# Collects the xcframework zips of one platform and writes checksums.txt plus a
# Package.swift snippet in the shape of media_kit_libs_{ios,macos}_video.
# Usage: package_release.sh <nix-result-dir> <ios|macos> <tag> <owner/repo> <out-dir>
set -euo pipefail
src=$1 os=$2 tag=$3 repo=$4 out=$5
prefix="libmpv-xcframeworks_${tag}_${os}-universal-video-default"
expected=(Ass Avcodec Avfilter Avformat Avutil Dav1d Freetype Fribidi Harfbuzz Mpv Png16 Swresample Swscale Uchardet Xml2)

mkdir -p "$out"
found=$(cd "$src" && ls ${prefix}_*.zip | sed "s/^${prefix}_//; s/\.zip$//" | sort | tr '\n' ' ')
want=$(printf '%s\n' "${expected[@]}" | sort | tr '\n' ' ')
if [ "$found" != "$want" ]; then
  echo "Unexpected framework set for $os:" >&2
  echo "  found: $found" >&2
  echo "  want:  $want" >&2
  exit 1
fi

: > "$out/checksums-$os.txt"
{
  echo "// Generated by labyrinth-apps/libmpv-builds (darwin-libmpv.yml) for $tag."
  echo "// Paste over libmpvArtifactBase + libmpvChecksums in"
  echo "// media_kit_libs_${os}_video/${os}/media_kit_libs_${os}_video/Package.swift."
  echo "let libmpvArtifactBase = \"https://github.com/${repo}/releases/download/${tag}/${prefix}\""
  echo "let libmpvChecksums = ["
} > "$out/Package-$os.swift.snippet"

n=${#expected[@]} i=0
for fw in "${expected[@]}"; do
  i=$((i + 1))
  zip="${prefix}_${fw}.zip"
  cp "$src/$zip" "$out/"
  sum=$(swift package compute-checksum "$out/$zip")
  [ "$sum" = "$(shasum -a 256 "$out/$zip" | cut -d' ' -f1)" ] || { echo "checksum mismatch for $zip" >&2; exit 1; }
  echo "$sum  $zip" >> "$out/checksums-$os.txt"
  sep=","; [ $i -eq $n ] && sep=""
  echo "    \"$fw\": \"$sum\"$sep" >> "$out/Package-$os.swift.snippet"
done
echo "]" >> "$out/Package-$os.swift.snippet"
cat "$out/checksums-$os.txt" "$out/Package-$os.swift.snippet"
